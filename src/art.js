// All sprites and scenery share the same hand-placed pixel grid.
function canvas(width, height, draw) {
  const image = document.createElement('canvas');
  image.width = width;
  image.height = height;
  const ctx = image.getContext('2d');
  const rect = (x, y, w, h, color) => { ctx.fillStyle = color; ctx.fillRect(x, y, w, h); };
  const poly = (points, color) => {
    ctx.fillStyle = color;
    ctx.beginPath();
    points.forEach(([x, y], i) => i ? ctx.lineTo(x, y) : ctx.moveTo(x, y));
    ctx.closePath();
    ctx.fill();
  };
  const pixelBox = (x, y, w, h, outline, fill) => {
    rect(x + 2, y, w - 4, h, outline);
    rect(x, y + 2, w, h - 4, outline);
    rect(x + 2, y + 2, w - 4, h - 4, fill);
  };
  draw({ rect, poly, pixelBox });
  return image;
}

